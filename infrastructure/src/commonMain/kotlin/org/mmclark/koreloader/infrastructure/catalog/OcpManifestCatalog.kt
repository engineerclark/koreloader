package org.mmclark.koreloader.infrastructure.catalog

import io.ktor.client.HttpClient
import io.ktor.client.request.get
import io.ktor.client.statement.bodyAsText
import io.ktor.http.isSuccess
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import org.mmclark.koreloader.domain.catalog.Artifact
import org.mmclark.koreloader.domain.catalog.Checksum
import org.mmclark.koreloader.domain.catalog.HashAlgorithm
import org.mmclark.koreloader.domain.catalog.InstallTarget
import org.mmclark.koreloader.domain.catalog.PackageCatalog
import org.mmclark.koreloader.domain.catalog.PackageId
import org.mmclark.koreloader.domain.catalog.PackageRelease

/**
 * [PackageCatalog] backed by NiLuJe's One-Click Packages manifest (generated by
 * kfmon `tools/upload.sh`). The container is re-uploaded on every release, so file names
 * are always resolved through the manifest, never hardcoded.
 */
class OcpManifestCatalog(
    private val client: HttpClient,
    private val manifestUrl: String = DEFAULT_MANIFEST_URL,
) : PackageCatalog {

    override suspend fun latestRelease(id: PackageId): PackageRelease? {
        val response = client.get(manifestUrl)
        if (!response.status.isSuccess()) throw IllegalStateException("Package list unavailable (HTTP ${response.status.value})")
        val manifest = json.decodeFromString<OcpManifestDto>(response.bodyAsText())
        return manifest.packages.firstOrNull { packageIdFor(it.name) == id }?.toRelease(id, manifest.storageUrl)
    }

    private fun OcpEntryDto.toRelease(id: PackageId, storageUrl: String) = PackageRelease(
        packageId = id,
        version = version,
        artifact = Artifact(
            fileName = filename,
            url = storageUrl.trimEnd('/') + "/" + path.trimStart('/'),
            sizeBytes = size,
            checksums = listOf(
                Checksum.of(HashAlgorithm.BLAKE2B_512, blake2b),
                Checksum.of(HashAlgorithm.MD5, md5),
            ),
        ),
        installTarget = InstallTarget.VOLUME_ROOT,
    )

    companion object {
        const val DEFAULT_MANIFEST_URL =
            "https://storage.gra.cloud.ovh.net/v1/AUTH_2ac4bfee353948ec8ea7fd1710574097/kfmon-pub/manifest.json"

        private val json = Json { ignoreUnknownKeys = true }

        private fun packageIdFor(manifestName: String): PackageId? = when (manifestName) {
            "KOReader" -> PackageId.KOREADER
            "Plato" -> PackageId.PLATO
            "Both" -> PackageId.KOREADER_AND_PLATO
            "KFMon" -> PackageId.KFMON
            else -> null
        }
    }
}

@Serializable
internal class OcpManifestDto(
    @SerialName("Storage_URL") val storageUrl: String,
    @SerialName("OCP") val packages: List<OcpEntryDto>,
)

@Serializable
internal class OcpEntryDto(
    val name: String,
    val version: String,
    val filename: String,
    val path: String,
    val size: Long,
    @SerialName("MD5") val md5: String,
    @SerialName("BLAKE2B") val blake2b: String,
)
