#!/usr/bin/env python3
"""
Generates the Android vector drawables for koreloader's branding from the SVGs in this folder:

  res/drawable/ic_launcher_foreground.xml   adaptive icon foreground (light mark, sized to the 66dp safe zone)
  res/drawable/ic_launcher_monochrome.xml   themed-icon layer (Android 13+)
  res/drawable/splash_logo.xml              launch screen: mark above wordmark, navy on light
  res/drawable-night/splash_logo.xml        same, light on navy
  res/drawable/lockup.xml                   mark + wordmark side by side, for the app's top bar
  res/drawable-night/lockup.xml             same, light palette for dark mode

Run from the repository root after changing the SVGs:  python3 branding/generate_drawables.py
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).parent
RES = HERE.parent / "androidApp/src/main/res"
SVG = "{http://www.w3.org/2000/svg}"

# Light-on-navy palette, as in koreloader-app-icon.svg.
ON_DARK = {"#12263A": "#F5F6F8", "#3D7BFF": "#6B9BFF", "#1F4FCC": "#3D6FE0"}
NAVY = "#12263A"


def num(v):
    return float(v)


def elements(svg_file):
    """Yields (pathData, fill, stroke, strokeWidth) for each shape of a flat SVG."""
    root = ET.parse(HERE / svg_file).getroot()
    for el in root.iter():
        tag = el.tag.replace(SVG, "")
        a = el.attrib
        if tag == "rect":
            x, y, w, h = (num(a[k]) for k in ("x", "y", "width", "height"))
            r = num(a.get("rx", 0))
            d = (f"M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} "
                 f"A{r},{r} 0 0 1 {x + w - r},{y + h} H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} "
                 f"V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z")
        elif tag == "line":
            d = f"M{a['x1']},{a['y1']} L{a['x2']},{a['y2']}"
        elif tag == "path":
            d = a["d"]
        elif tag == "polygon":
            pts = a["points"].split()
            d = "M" + " L".join(pts) + " Z"
        else:
            continue
        yield d, a.get("fill"), a.get("stroke"), a.get("stroke-width")


def path_xml(d, fill, stroke, width, palette, mono):
    def color(c):
        return "#FFFFFFFF" if mono else palette.get(c, c)
    attrs = [f'android:pathData="{d}"']
    if fill and fill != "none":
        attrs.append(f'android:fillColor="{color(fill)}"')
    if stroke:
        attrs += [f'android:strokeColor="{color(stroke)}"', f'android:strokeWidth="{width}"']
    return "<path " + " ".join(attrs) + "/>"


def group(svg_file, scale, tx, ty, palette=None, mono=False):
    paths = "\n        ".join(path_xml(*e, palette or {}, mono) for e in elements(svg_file))
    return (f'<group android:scaleX="{scale:.5f}" android:scaleY="{scale:.5f}" '
            f'android:translateX="{tx:.4f}" android:translateY="{ty:.4f}">\n        {paths}\n    </group>')


def vector(size, groups, comment):
    body = "\n    ".join(groups)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} Generated by branding/generate_drawables.py; do not edit. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp" android:height="{size}dp"\n'
            f'    android:viewportWidth="{size}" android:viewportHeight="{size}">\n    {body}\n</vector>\n')


# Visual bounds of the mark in its own coordinates (stroke included): x 39..161, y 5..201.
MARK_W, MARK_H, MARK_CX, MARK_CY = 122.0, 196.0, 100.0, 103.0
# Wordmark glyph bounds in koreloader-wordmark.svg: x 10..578.41, y 10..94.25.
WORD_X0, WORD_Y0, WORD_W, WORD_H = 10.0, 10.0, 568.41, 84.25


def launcher(mono):
    # 108dp canvas; mark ~53dp tall (≈74% of the 72dp visible area, like the 512px app icon), centred.
    s = 53.0 / MARK_H
    g = group("koreloader-mark.svg", s, 54 - MARK_CX * s, 54 - MARK_CY * s, ON_DARK, mono)
    return vector(108, [g], "Adaptive launcher icon " + ("monochrome layer." if mono else "foreground (background: @color/ic_launcher_background)."))


def splash(palette):
    # 288dp canvas; Android masks the icon to a 192dp circle, so the lockup must fit inside it.
    word_w = 140.0
    ws = word_w / WORD_W
    word_h = WORD_H * ws
    mark_h, gap = 96.0, 12.0
    ms = mark_h / MARK_H
    total = mark_h + gap + word_h
    top = 144 - total / 2
    mark = group("koreloader-mark.svg", ms, 144 - MARK_CX * ms, top + mark_h / 2 - MARK_CY * ms, palette)
    word = group("koreloader-wordmark.svg", ws, 144 - word_w / 2 - WORD_X0 * ws, top + mark_h + gap - WORD_Y0 * ws, palette)
    # Sanity: the wordmark's outer corners must lie within the 96dp-radius circle.
    corner = ((word_w / 2) ** 2 + (total / 2) ** 2) ** 0.5
    assert corner <= 96, f"lockup corner at {corner:.1f}dp leaves the 96dp splash circle"
    return vector(288, [mark, word], "Launch screen icon: mark above wordmark.")


def lockup(palette):
    # koreloader-lockup.svg viewBox: 24 -10 771.41 226 (mark and wordmark side by side).
    vb_x, vb_y, vb_w, vb_h = 24.0, -10.0, 771.41, 226.0
    height_dp = 32.0
    width_dp = height_dp * vb_w / vb_h
    g = group("koreloader-lockup.svg", 1.0, -vb_x, -vb_y, palette)
    return (vector(0, [g], "Top bar lockup.")
            .replace('android:width="0dp" android:height="0dp"', f'android:width="{width_dp:.2f}dp" android:height="{height_dp:.0f}dp"')
            .replace('android:viewportWidth="0" android:viewportHeight="0"', f'android:viewportWidth="{vb_w}" android:viewportHeight="{vb_h}"'))


outputs = {
    "drawable/ic_launcher_foreground.xml": launcher(mono=False),
    "drawable/ic_launcher_monochrome.xml": launcher(mono=True),
    "drawable/splash_logo.xml": splash({}),
    "drawable-night/splash_logo.xml": splash(ON_DARK),
    "drawable/lockup.xml": lockup({}),
    "drawable-night/lockup.xml": lockup(ON_DARK),
}
for rel, text in outputs.items():
    path = RES / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path.relative_to(HERE.parent))
